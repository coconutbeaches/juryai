/* ------------------------------------------------------------------------ */
/* Trusted request context                                                   */
/* ------------------------------------------------------------------------ */

/**
 * The authenticated principal, resolved by the transport from a session. A
 * principal id appearing anywhere in external tool input is data, never
 * identity, and this runtime never reads one from a command.
 */
export interface RuntimePrincipal {
  principal_id: string;
}

export interface RuntimeRequestContext {
  principal: RuntimePrincipal;
  /**
   * Where the text reached JuryAI from. Resolved by the transport, never by
   * the caller: relayed input cannot promote itself to first-party
   * provenance by asking. Defaults to the relay channel.
   */
  source_channel?: SourceChannel;
  /** Relay's self-reported identity. Recorded for the record, never trusted. */
  relaying_agent?: string | null;
}

/**
 * The runtime's own start command. It intentionally mirrors, rather than
 * imports, the transport DTO: `client_request_id` is adapter-issued transport
 * metadata identifying the OPERATION, and the runtime owns what that means
 * without depending on the tools layer.
 */
export interface StartCaseCommand {
  client_request_id: string;
}

/**
 * Per-call execution context. Deliberately separate from the command: an
 * `AbortSignal` is how the caller is still listening, not something the case
 * records. Nothing here ever reaches canonical state.
 */
export interface RuntimeCallOptions {
  signal?: AbortSignal;
}

export interface GetCaseStateQuery {
  /** Omitted means "the authenticated principal's active draft". */
  case_id?: string;
}

export interface SubmitTurnCommand {
  case_id: string;
  expected_case_version: number;
  in_reply_to: string[];
  payload: SourceTurnPayload;
  /** Adapter-minted retry key. Never generated by a model. */
  client_turn_id: string | null;
  /** Self-reported by the relay. Recorded, never trusted. */
  source_language?: string | null;
  translation_indicated?: boolean;
}

