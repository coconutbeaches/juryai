/**
 * A turn already in the case that carries this request's replay identity, but
 * whose idempotency record is absent from the replay-store read.
 *
 * Identity follows the same hierarchy used everywhere else:
 *  - an exact, non-null `client_turn_id` is operation identity and qualifies
 *    regardless of the heuristic window;
 *  - otherwise content fingerprint AND provenance must agree, and the turn must
 *    fall inside the heuristic replay window. The window is measured from the
 *    turn's server receipt time, since the record that would normally carry
 *    `recorded_at_ms` is exactly what is missing.
 *
 * Old same-content statements outside the window are therefore NOT flagged:
 * they are ordinary history, and treating them as inconsistency would block a
 * legitimate later submission forever.
 */
function replayIdentityTurnMissingRecord(args: {
  state: CaseState;
  records: readonly IdempotencyRecord[];
  request: SubmitRequest;
  requestProvenance: string;
  contentFingerprint: string;
  now_ms: number;
  window_ms: number;
}): SourceTurnRecord | undefined {
  const recorded = new Set(args.records.map((record) => record.turn_id));
  return args.state.turn_log.find((turn) => {
    if (turn.principal_id !== args.request.principal_id) return false;
    if (recorded.has(turn.turn_id)) return false;
    if (
      args.request.client_turn_id !== null &&
      turn.client_turn_id === args.request.client_turn_id
    ) {
      return true;
    }
    if (turn.request_fingerprint !== args.contentFingerprint) return false;
    if (provenanceKey(turn) !== args.requestProvenance) return false;
    const receivedMs = Date.parse(turn.received_at);
    return Number.isFinite(receivedMs) && args.now_ms - receivedMs <= args.window_ms;
  });
}

/**
 * May a stored replay record stand in for THIS request?
 *
 * An exact `client_turn_id` is network-operation identity and outranks every
 * content heuristic: a caller retrying the same id replays even if transport
 * metadata drifted between attempts. Only the heuristic fingerprint path is
 * narrowed by provenance.
 */
function sharesSourceIdentity(
  record: IdempotencyRecord,
  request: SubmitRequest,
  requestProvenance: string,
  state: CaseState,
): boolean {
  if (request.client_turn_id !== null && record.client_turn_id === request.client_turn_id) {
    return true;
  }
  const turn = state.turn_log.find((entry) => entry.turn_id === record.turn_id);
  // The record's turn is not in the case we loaded — the stale-read race the
  // replay refresh exists for. We cannot show the provenance differs, and
  // excluding on uncertainty would turn a lost-response retry into a duplicate
  // write, so the record stays eligible. The refresh re-checks provenance once
  // the turn becomes visible, and restarts the attempt if it does not match.
  if (!turn) return true;
  return provenanceKey(turn) === requestProvenance;
}

/**
 * An adapter-issued operation id. One rule for `client_request_id` and
 * `client_turn_id` so the two cannot drift: a non-empty string with at least
 * one non-whitespace character. The value is validated, never normalised — the
 * id is stored exactly as the adapter sent it, because exact identity is the
 * whole point of it.
 */
function isClientIssuedId(value: unknown): value is string {
  return typeof value === 'string' && value.trim().length > 0;
}

/** Relay self-reports carried alongside a submission. Recorded, never trusted. */
interface RelayClaims {
  source_language: string | null;
  translation_indicated: boolean;
}

/**
 * Canonical identity of where a submission came from. `null` and absent
 * collapse to the same value, so an adapter that omits a field and one that
 * sends it as null describe the same source event rather than two.
 */
function provenanceKey(source: {
  source_channel: SourceChannel;
  relaying_agent: string | null;
  source_language: string | null;
  translation_indicated: boolean;
}): string {
  return canonicalSerialize({
    source_channel: source.source_channel,
    relaying_agent: source.relaying_agent ?? null,
    source_language: source.source_language ?? null,
    translation_indicated: source.translation_indicated === true,
  });
}

/**
 * A storage failure is opaque to the caller and retryable. Table names, driver
 * text and stack detail go to the diagnostics sink, never across the boundary.
 */
function unavailable(message: string): RuntimeFailure {
  return failure('INTERNAL_ERROR', message + ' Try again.', true);
}

function principalOf(context: RuntimeRequestContext): string | null {
  const value = context.principal?.principal_id;
  return typeof value === 'string' && value.trim().length > 0 ? value : null;
}

function resolveRecorded(propositions: readonly Proposition[], ids: readonly string[]) {
  const byId = new Map(
    propositions.map((proposition) => [proposition.proposition_id, proposition]),
  );
  return ids
    .map((id) => byId.get(id))
    .filter((proposition): proposition is Proposition => proposition !== undefined)
    .map(interpretationSlot);
}

function wellFormedCommand(command: SubmitTurnCommand): boolean {
  if (typeof command.case_id !== 'string' || command.case_id.trim().length === 0) return false;
  if (!Array.isArray(command.in_reply_to)) return false;
  if (command.in_reply_to.some((value) => typeof value !== 'string' || value.length === 0)) {
    return false;
  }
  // `null` means "no exact transport retry identity, heuristic fallback may
  // apply" and stays valid. An empty or blank string is not an identity at
  // all: committed as one, every later submission carrying the same blank key
  // exact-matches the first operation and replays its result regardless of
  // text, requirements, provenance or version — silently dropping a real
  // answer. It is refused rather than repaired into `null`, because an adapter
  // that sends one is broken and should be told so.
  if (command.client_turn_id !== null && !isClientIssuedId(command.client_turn_id)) return false;
  const payload: unknown = command.payload;
  if (typeof payload !== 'object' || payload === null) return false;
  const { context, answer } = payload as Partial<SourceTurnPayload>;
  if (!Array.isArray(context)) return false;
  if (context.some((message) => typeof message?.text !== 'string')) return false;
  return typeof answer?.text === 'string';
}

function buildWarnings(
  acceptedCount: number,
  facts: { opened: number; translated: boolean },
): string[] {
  const warnings: string[] = [];
  if (facts.opened > 0) {
    warnings.push('JuryAI needs a clarification before it can record an answer to that question.');
  } else if (acceptedCount === 0) {
    warnings.push('JuryAI did not record a canonical statement from that answer.');
  }
  if (facts.translated) {
    // Span fidelity is a claim about the material JuryAI received. A relay that
    // says it translated the answer has removed that claim's meaning, and the
    // record says so rather than quietly keeping the same standing.
    warnings.push(
      'That answer was relayed as a translation, so JuryAI cannot tie its wording to the words you used.',
    );
  }
  return warnings;
}
